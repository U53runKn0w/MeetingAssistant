先介绍一下RBAC模型的设计：

RBAC模型概念：
RBAC（Role-Based Access Control，基于角色的访问控制）是一种权限管理模型，通过角色将用户和权限关联起来。用户拥有一个或多个角色，每个角色拥有一个或多个权限。

模型设计：

1. 用户（User）
   - 用户ID
   - 用户名
   - 用户类型
   - 用户状态
   - 所属组织
   - 创建时间
   - 更新时间

2. 角色（Role）
   - 角色ID
   - 角色名称
   - 角色描述
   - 角色类型
   - 角色状态
   - 创建时间
   - 更新时间

3. 权限（Permission）
   - 权限ID
   - 权限名称
   - 权限描述
   - 权限类型（菜单权限、按钮权限、数据权限、API权限）
   - 权限资源（如：/api/meeting）
   - 权限操作（如：GET, POST, PUT, DELETE）
   - 创建时间
   - 更新时间

4. 用户角色关系（UserRole）
   - 关系ID
   - 用户ID
   - 角色ID
   - 授权时间
   - 授权人

5. 角色权限关系（RolePermission）
   - 关系ID
   - 角色ID
   - 权限ID
   - 授权时间
   - 授权人

权限类型：

1. 菜单权限：控制用户能够访问哪些菜单和页面
   - 例如：用户只能访问"我的会议"菜单，不能访问"系统设置"菜单

2. 按钮权限：控制用户能够执行哪些操作
   - 例如：用户可以查看会议，但不能删除会议

3. 数据权限：控制用户能够访问哪些数据
   - 例如：用户只能查看自己创建的会议，不能查看其他人创建的会议

4. API权限：控制用户能够调用哪些API接口
   - 例如：用户只能调用GET /api/meeting接口，不能调用DELETE /api/meeting接口

权限粒度：

1. 粗粒度权限：
   - 按功能模块划分，如"会议管理"、"用户管理"
   - 适用于简单的权限控制

2. 中粒度权限：
   - 按具体操作划分，如"创建会议"、"编辑会议"、"删除会议"
   - 适用于中等复杂度的权限控制

3. 细粒度权限：
   - 按具体数据划分，如"只能查看自己创建的会议"、"只能查看本周的会议"
   - 适用于复杂的权限控制

我们的权限系统支持三种粒度的权限，根据业务场景灵活使用。

数据权限设计：

数据权限是RBAC模型的扩展，用于控制用户能够访问哪些数据。我们支持以下几种数据权限规则：

1. 全部数据：可以访问所有数据
2. 本部门数据：只能访问本部门的数据
3. 本部门及以下数据：可以访问本部门及子部门的数据
4. 仅本人数据：只能访问自己创建的数据
5. 自定义数据：自定义数据范围，如"本周数据"、"本季度数据"等

数据权限规则可以组合使用，例如：
- 本部门数据 + 仅本人数据：可以访问本部门同事的数据和自己创建的数据
- 本部门及以下数据 + 自定义数据（本周）：可以访问本部门及子部门本周的数据

权限继承：

权限继承是指子用户可以继承父用户的权限。我们支持以下两种权限继承：

1. 组织架构继承：下级部门可以继承上级部门的权限
   - 例如：研发部可以继承技术部的权限

2. 角色继承：子角色可以继承父角色的权限
   - 例如："开发工程师"角色可以继承"普通用户"角色的权限

动态权限：

动态权限是指根据上下文动态计算权限。我们支持以下几种动态权限：

1. 基于时间的权限：在某些时间段内有效
   - 例如：临时管理员权限，仅在指定时间内有效

2. 基于地点的权限：在某些地点有效
   - 例如：只有在公司内网才能访问某些资源

3. 基于设备的权限：在某些设备上有效
   - 例如：只能在公司设备上访问敏感数据

动态权限可以通过规则引擎实现，规则引擎根据上下文信息计算用户是否拥有权限。

权限缓存：

为了保证性能，我们对权限数据进行缓存：

1. 用户角色缓存：缓存用户拥有的角色
2. 角色权限缓存：缓存角色拥有的权限
3. 权限检查结果缓存：缓存权限检查的结果

缓存策略：
- 热点数据长期缓存（如常用的角色和权限）
- 冷数据短期缓存（如不常用的角色和权限）
- 缓存失效策略：当权限数据变更时，清除相关缓存

权限审计：

我们记录所有权限相关的操作日志，包括：
1. 用户角色分配日志
2. 角色权限分配日志
3. 权限检查日志
4. 权限变更日志

审计日志用于：
1. 安全审计：发现和追溯安全事件
2. 合规审查：满足合规要求
3. 问题排查：排查权限相关问题

